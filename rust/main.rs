//! Thin CLI adapter over the reusable core. No GUI.
use pd2_price_filter::{
    base_codes, cache, cli, filter, fixed, io, pricing, roster, types::PricedItem,
};
use std::{
    path::{Path, PathBuf},
    process::ExitCode,
};

const DATA_DIR_DEFAULT: &str = "data";
const PACE: std::time::Duration = std::time::Duration::from_millis(150);
const MAX_FILTER_BYTES: u64 = 32 * 1024 * 1024;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("Error: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.iter().any(|a| a == "--help" || a == "-h") {
        print_help();
        return Ok(());
    }
    let options = cli::parse(args)?;
    let mode = if options.mode == "softcore" {
        pricing::Mode::Softcore
    } else {
        pricing::Mode::Hardcore
    };
    let data_dir = options
        .values
        .get("--data-dir")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("PD2_PRICE_FILTER_DATA").map(PathBuf::from))
        .unwrap_or_else(|| PathBuf::from(DATA_DIR_DEFAULT));

    let source_bytes = io::read_bounded(&options.source, MAX_FILTER_BYTES).map_err(|e| {
        let mut message = format!(
            "Source filter unreadable: {}: {e}",
            options.source.display()
        );
        if let Ok(entries) = std::fs::read_dir(options.source.parent().unwrap_or(Path::new("."))) {
            let mut names: Vec<_> = entries
                .flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .filter(|n| n.ends_with(".filter"))
                .collect();
            names.sort();
            if !names.is_empty() {
                message.push_str(&format!(
                    "\nAvailable filters in {}:",
                    options.source.parent().unwrap_or(Path::new(".")).display()
                ));
                for n in names {
                    message.push_str(&format!("\n  {n}"));
                }
            }
        }
        message
    })?;
    let filter_text = String::from_utf8(source_bytes)
        .map_err(|_| "Source filter is not valid UTF-8; refusing a lossy conversion".to_string())?;
    if filter_text.contains("generated by pd2_lootfilter") {
        return Err("Source already contains a generated block. Use the author's original filter, not a previous output.".into());
    }
    println!("Mode: {mode:?}  |  Source: {}", options.source.display());

    let client = (!options.offline).then(pricing::Client::new).transpose()?;
    let roster = if let Some(path) = options.values.get("--roster-file") {
        let bytes = io::read_bounded(Path::new(path), 64 * 1024 * 1024)?;
        let value: serde_json::Value =
            serde_json::from_slice(&bytes).map_err(|e| format!("{path}: invalid JSON: {e}"))?;
        roster::parse_roster(&value)?
    } else {
        let client = client.as_ref().ok_or("--offline needs --roster-file")?;
        println!("Fetching roster...");
        client.fetch_roster()?
    };
    println!("  {} uniques/sets", roster.len());

    let base_path = data_dir.join("base-codes.json");
    let mut base_cache = load_base_cache(&base_path)?;
    if options.refresh_bases {
        base_cache = Default::default();
    }
    if !options.offline {
        let client = client.as_ref().expect("client exists when online");
        let result =
            base_codes::refresh_cache(&roster, &mut base_cache, client, |m| println!("{m}"));
        save_json_atomic(&base_path, &base_cache)?;
        result?;
    }

    let fixed_path = options
        .values
        .get("--fixed-items")
        .map(PathBuf::from)
        .unwrap_or_else(|| data_dir.join("pd2trader-items.json"));
    let fixed_defs = fixed::parse_fixed_items(&io::read_bounded(&fixed_path, 8 * 1024 * 1024)?)?;
    let mut names: Vec<String> = roster.keys().cloned().collect();
    names.extend(fixed_defs.iter().map(|d| d.name.clone()));

    let price_path = data_dir.join(format!("price-cache-{}.json", options.mode));
    let mut price_cache = if let Some(path) = options.values.get("--prices-file") {
        let bytes = io::read_bounded(Path::new(path), 32 * 1024 * 1024)?;
        serde_json::from_slice(&bytes).map_err(|e| format!("{path}: invalid price cache: {e}"))?
    } else if options.refresh {
        // Refresh replaces per-item results; existing successes survive failures.
        cache::load_price_cache(&price_path)?
    } else {
        cache::load_price_cache(&price_path)?
    };
    println!("Pricing {} items from pd2trader ({mode:?})...", names.len());
    let now = time::OffsetDateTime::now_utc();
    let gathered = if options.offline {
        // Offline is an explicit developer/test mode: reuse every cached price,
        // including stale ones, and never fall back silently in online mode.
        let prices = names
            .iter()
            .filter_map(|name| {
                price_cache
                    .get(name)
                    .and_then(cache::entry_price)
                    .map(|p| (name.clone(), p))
            })
            .collect();
        cache::Gathered {
            prices,
            failures: 0,
        }
    } else {
        let client = client.as_ref().expect("client exists when online");
        cache::gather_prices(
            &names,
            &mut price_cache,
            options.refresh,
            now,
            |name| client.fetch_average(name, mode),
            || std::thread::sleep(PACE),
        )
    };
    save_json_atomic(&price_path, &price_cache)?;
    if gathered.failures > names.len() / 2 {
        return Err(format!(
            "Aborting: {}/{} price requests failed; pd2trader may be down. No filter written.",
            gathered.failures,
            names.len()
        ));
    }

    let mut items = filter::resolve_priced_items(&roster, &base_cache, &gathered.prices);
    items.extend(fixed::resolve_fixed_items(&fixed_defs, &gathered.prices));
    let decorated = filter::decorate(&filter_text, &items);
    io::write_derivative(
        &options.source,
        &options.output,
        decorated.as_bytes(),
        options.overwrite,
        &std::sync::atomic::AtomicBool::new(false),
    )?;

    let count = |kind: &str, category: Option<&str>| {
        items
            .iter()
            .filter(|i| match (i, kind, category) {
                (PricedItem::Unique { .. }, "unique", _) | (PricedItem::Set { .. }, "set", _) => {
                    true
                }
                (PricedItem::Fixed { category: c, .. }, "fixed", Some(want)) => c == want,
                _ => false,
            })
            .count()
    };
    println!("\nWrote: {}", options.output.display());
    println!(
        "  {} uniques, {} sets, {} runes, {} ubers",
        count("unique", None),
        count("set", None),
        count("fixed", Some("rune")),
        count("fixed", Some("uber"))
    );
    println!(
        "  {} priced, {} fetch failures",
        gathered.prices.len(),
        gathered.failures
    );
    if !options.overwrite {
        println!("  (existing output replacement requires --overwrite when present)");
    }
    Ok(())
}

fn load_base_cache(path: &Path) -> Result<pd2_price_filter::types::BaseCodeCache, String> {
    if !path.exists() {
        return Ok(Default::default());
    }
    let bytes = io::read_bounded(path, 16 * 1024 * 1024)?;
    serde_json::from_slice(&bytes)
        .map_err(|e| format!("{}: invalid base-code cache: {e}", path.display()))
}

fn save_json_atomic(path: &Path, value: &impl serde::Serialize) -> Result<(), String> {
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    let mut bytes = serde_json::to_vec_pretty(value).map_err(|e| e.to_string())?;
    bytes.push(b'\n');
    io::atomic_write(path, &bytes)
}

fn print_help() {
    println!(
        "pd2-price-filter — add approximate PD2 market prices to a separate filter copy\n\
\nUsage: pd2-price-filter [FILTER] [--softcore] [--refresh-prices] [--refresh-bases]\n\
       [--source PATH] [--output PATH] [--data-dir DIR] [--overwrite] [--offline --roster-file FILE]\n\
\nDefaults preserve the original CLI: hardcore ladder and the Windows PD2 filters paths.\n\
Prices are approximate median listing prices, not valuations of individual rolls.\n\
The source filter is never modified; the potion override has been removed."
    );
}
